// Builds the deployable admin panel at admin-panel/index.html from the Edge
// Function's source template (supabase/functions/admin/index.html).
//
// The template keeps placeholders so it can be served by the `admin` function
// locally; the published copy needs the project's own URL and publishable anon
// key baked in. Those come from desktop/.env.production.local (gitignored), so
// no secret is duplicated by hand. The anon key is the RLS-scoped publishable
// kind — the same value the desktop bundle ships — and it grants nothing on its
// own: every money and key-pool RPC is service-role only.
//
//   node scripts/gen-admin-panel.mjs
import { readFileSync, writeFileSync, mkdirSync, statSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const srcPath = join(root, "supabase", "functions", "admin", "index.html");
const envPath = join(root, "desktop", ".env.production.local");
const outDir = join(root, "admin-panel");
const outPath = join(outDir, "index.html");

const env = readFileSync(envPath, "utf8");
const url = /^VITE_SUPABASE_URL=(\S+)$/m.exec(env)?.[1];
const key = /^VITE_SUPABASE_ANON_KEY=(\S+)$/m.exec(env)?.[1];
if (!url || !key) throw new Error(`${envPath} has no VITE_SUPABASE_URL / VITE_SUPABASE_ANON_KEY`);
if (!/^https:\/\/[a-z0-9-]+\.supabase\.co$/.test(url)) throw new Error(`unexpected url: ${url}`);

let html = readFileSync(srcPath, "utf8");
const before = html;
html = html
  .replace('const SUPABASE_URL = "https://YOUR-PROJECT.supabase.co";', `const SUPABASE_URL = "${url}";`)
  .replace('const SUPABASE_ANON_KEY = "YOUR-ANON-KEY";', `const SUPABASE_ANON_KEY = "${key}";`);
if (html === before) throw new Error("placeholder lines did not match — the panel template changed shape");
if (html.includes("YOUR-ANON-KEY") || html.includes("YOUR-PROJECT")) {
  throw new Error("a placeholder survived the substitution");
}

mkdirSync(outDir, { recursive: true });
writeFileSync(
  outPath,
  `<!-- GENERATED by scripts/gen-admin-panel.mjs from supabase/functions/admin/index.html.
     Do not edit here — edit the template and regenerate. -->\n` + html
);
console.log("wrote", outPath, statSync(outPath).size, "bytes for", url);
